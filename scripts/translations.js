const fs = require('node:fs');
const path = require('node:path');

function bundleTranslations() {
  const root = path.resolve(__dirname, '..');
  const translations = {};
  for (const name of ['page', 'content', 'messages']) {
    const entries = JSON.parse(fs.readFileSync(path.join(root, 'locales', `${name}.en.json`), 'utf8'));
    for (const [source, translation] of Object.entries(entries)) {
      if (typeof translation !== 'string' || !translation.trim()) throw new Error(`Missing English translation: ${source}`);
      // Page copy takes precedence for phrases shared with data and messages.
      if (!(source in translations)) translations[source] = translation;
    }
  }
  const output = `/* Generated by scripts/translations.js from locales/*.en.json. */\nwindow.VMAA_EN = ${JSON.stringify(translations, null, 2)};\n`;
  fs.writeFileSync(path.join(root, 'translations.en.js'), output);
  return translations;
}

if (require.main === module) bundleTranslations();
module.exports = { bundleTranslations };
